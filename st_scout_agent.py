# --- SERP Baseline Benchmarks ---
SERP_BASELINE_CTR = {
    1: 0.28,
    2: 0.15,
    3: 0.10,
    4: 0.065,
    5: 0.050,
    6: 0.035,
    7: 0.025,
    8: 0.020,
    9: 0.015,
    10: 0.012
}

def get_expected_ctr(position: float) -> float:
    pos_int = max(1, min(10, int(round(position))))
    return SERP_BASELINE_CTR.get(pos_int, 0.01)

# --- Tool 1: DuckDB Telemetry Perception Tool ---
def query_telemetry_anomalies(db_conn, min_impressions: int = 2000, ctr_ratio_threshold: float = 0.5):
    """
    Scans DuckDB search console telemetry for high-volume queries with suppressed CTR.
    """
    print(f"[TOOL] Ingesting DuckDB Telemetry (min_impressions={min_impressions})...")
    query = f"""
    SELECT 
        query,
        impressions,
        clicks,
        round(ctr, 4) as ctr,
        round(avg_position, 1) as avg_position,
        current_title,
        trend
    FROM search_telemetry
    WHERE impressions >= {min_impressions}
    ORDER BY impressions DESC
    """
    df = db_conn.execute(query).fetchdf()
    anomalies = []
    for _, row in df.iterrows():
        expected_ctr = get_expected_ctr(row['avg_position'])
        ratio = row['ctr'] / expected_ctr if expected_ctr > 0 else 1.0
        if ratio < ctr_ratio_threshold:
            anomalies.append({
                "query": row['query'],
                "impressions": int(row['impressions']),
                "clicks": int(row['clicks']),
                "actual_ctr": float(row['ctr']),
                "expected_ctr": round(expected_ctr, 4),
                "ratio": round(ratio, 2),
                "avg_position": float(row['avg_position']),
                "current_title": str(row['current_title']),
                "trend": str(row['trend'])
            })
    print(f"[TOOL] Detected {len(anomalies)} statistically significant CTR anomalies.")
    return anomalies

